/**
 * Pure helper functions for the roadmap day view.
 * Plain ES modules without JSX or browser/DOM dependencies.
 */

/**
 * Strips "Phase N:" or "Phase N -" prefix from a phase title.
 * @param {string} title
 * @returns {string}
 */
export function stripPhasePrefix(title) {
  if (!title || typeof title !== 'string') return '';
  return title.replace(/^Phase\s+\d+\s*[:\-–—]\s*/i, '').trim();
}

/**
 * Computes cumulative start and end minute ranges for time blocks.
 * @param {Array<{ minutes?: number }>} blocks
 * @returns {Array<object>}
 */
export function computeTimeRanges(blocks) {
  if (!Array.isArray(blocks)) return [];
  let currentStart = 0;
  return blocks.map((block) => {
    const mins = Math.max(0, Number(block?.minutes) || 0);
    const start = currentStart;
    const end = start + mins;
    currentStart = end;
    return {
      ...block,
      startMinutes: start,
      endMinutes: end,
      timeRangeLabel: `${start} to ${end}`
    };
  });
}

/**
 * Determines whether a topic summary is just an autogenerated placeholder.
 * Placeholders look like: "Study and practical application of <title>." or are empty.
 * @param {string} summary
 * @param {string} title
 * @returns {boolean}
 */
export function isPlaceholderSummary(summary, title) {
  if (!summary || typeof summary !== 'string') return true;
  const cleanSummary = summary.trim().toLowerCase();
  if (!cleanSummary) return true;

  if (title && typeof title === 'string') {
    const cleanTitle = title.trim().toLowerCase();
    const placeholderPattern = `study and practical application of ${cleanTitle}`;
    const placeholderPatternDot = `study and practical application of ${cleanTitle}.`;
    if (cleanSummary === placeholderPattern || cleanSummary === placeholderPatternDot) {
      return true;
    }
  }
  return false;
}

/**
 * Finds the first unfinished task's dayNumber.
 * @param {Array<{ id: string, task: { dayNumber: number } }>} tasks
 * @param {Record<string, boolean>} completedTasksMap
 * @returns {number|null} dayNumber or null if all completed or empty
 */
export function getNextUnfinishedDay(tasks, completedTasksMap = {}) {
  if (!Array.isArray(tasks) || tasks.length === 0) return null;
  for (const item of tasks) {
    if (!item?.task) continue;
    if (!completedTasksMap[item.id]) {
      return item.task.dayNumber;
    }
  }
  return null;
}

/**
 * Groups and enriches phases with clean titles, counts, and day lists.
 * @param {Array<object>} phases
 * @param {Record<number, Array<object>>} tasksByPhase
 * @param {Record<string, boolean>} completedTasksMap
 * @returns {Array<object>}
 */
export function computePhaseSummaries(phases = [], tasksByPhase = {}, completedTasksMap = {}) {
  if (!Array.isArray(phases)) return [];
  return phases.map((phase, pIdx) => {
    const rawTitle = phase.phaseTitle || phase.phase || `Phase ${pIdx + 1}`;
    const cleanTitle = stripPhasePrefix(rawTitle);
    const tasks = tasksByPhase[pIdx] || [];
    const totalDays = tasks.length;
    const completedDays = tasks.filter(t => completedTasksMap[t.id]).length;
    const isCompleted = totalDays > 0 && completedDays === totalDays;

    let firstUnfinishedDay = null;
    for (const t of tasks) {
      if (!completedTasksMap[t.id]) {
        firstUnfinishedDay = t.task.dayNumber;
        break;
      }
    }

    const percent = totalDays > 0 ? Math.round((completedDays / totalDays) * 100) : 0;

    return {
      phaseIndex: pIdx,
      phaseNumber: phase.phaseNumber || (pIdx + 1),
      rawTitle,
      cleanTitle,
      totalDays,
      completedDays,
      isCompleted,
      firstUnfinishedDay: firstUnfinishedDay ?? (tasks[0]?.task?.dayNumber || 1),
      percent,
      tasks
    };
  });
}
